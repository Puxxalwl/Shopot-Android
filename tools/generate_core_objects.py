#!/usr/bin/env python3
"""Generate typed Kotlin objects from shopot-core's CORE-API.md.

The generator is deliberately dependency-free. It extracts the stable numeric
method/event/status contracts and the canonical limits table from the checked-
out core submodule. It fails on an empty or malformed contract instead of
silently generating stale client code.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "core-src" / "core" / "docs" / "CORE-API.md"
OUT = ROOT / "data" / "src" / "main" / "java" / "com" / "stille" / "coreapi" / "GeneratedCoreApi.kt"

METHOD_RE = re.compile(r"\|\s*`([A-Z][A-Z0-9_]*)`\s*\|\s*(\d+)\s*\|")
STATUS_RE = re.compile(r"\|\s*(\d+)\s*\|\s*`([A-Z][A-Z0-9_]*)`\s*\|")
EVENT_RE = METHOD_RE
LIMIT_RE = re.compile(r"\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|")


def clean_name(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value.strip()).strip("_").upper()


def main() -> None:
    if not SPEC.is_file():
        raise SystemExit(f"missing core API spec: {SPEC}")
    text = SPEC.read_text(encoding="utf-8")

    service_start = text.index("### 4.1 Service")
    events_start = text.index("## 5. Events")
    status_start = text.index("## 3. Status codes")
    limits_start = text.index("## 6. Limits")

    method_text = text[service_start:events_start]
    event_text = text[events_start:limits_start]
    status_text = text[status_start:service_start]
    limits_text = text[limits_start:text.index("## 7. Delivery model")]

    version_match = re.search(r"API version:\s*\*\*(\d+\.\d+\.\d+)\*\*", text)
    api_version = version_match.group(1) if version_match else "unknown"

    methods = [(name, int(number)) for name, number in METHOD_RE.findall(method_text)]
    methods += [(name, int(number)) for name, number in re.findall(r"####\s+`([A-Z][A-Z0-9_]*)`\s+\((\d+)", method_text)]
    # API 2.7 additions are grouped in prose, not standalone headings.
    methods += [(name, int(number)) for name, number in re.findall(r"`([A-Z][A-Z0-9_]*)`\s+\((\d+)\)", method_text)]
    # Grouped reaction heading is an explicit two-method contract.
    if "SET_REACTION" in method_text and "REMOVE_REACTION" in method_text:
        methods += [("SET_REACTION", 8), ("REMOVE_REACTION", 9)]
    events = [(name, int(number)) for name, number in EVENT_RE.findall(event_text)]
    # Event 15–17 names are specified in prose after the event table.
    events += [("CONTACT_STATE_CHANGED", 15), ("CONTACTS_CHANGED", 16), ("CONTACT_UPSERTED", 17)] if "CONTACT_STATE_CHANGED" in event_text else []
    statuses = [(name, int(number)) for number, name in STATUS_RE.findall(status_text)]
    statuses += [("RESYNC_REQUIRED", 21)] if "RESYNC_REQUIRED" in text else []
    limits = []
    for left, right in LIMIT_RE.findall(limits_text):
        key = clean_name(left)
        if key in {"LIMIT", ""}:
            continue
        value = right.strip().split("(", 1)[0].strip()
        limits.append((key, value))

    # Deduplicate methods where the spec groups SET/REMOVE_REACTION in one row.
    methods = sorted(dict.fromkeys(methods), key=lambda item: item[1])
    events = sorted(dict.fromkeys(events), key=lambda item: item[1])
    statuses = sorted(dict.fromkeys(statuses), key=lambda item: item[1])
    if len(methods) < 20 or len(events) < 10 or len(statuses) < 10:
        raise SystemExit("CORE-API parse produced too few contracts; refusing to generate")

    def entries(rows: list[tuple[str, int]]) -> str:
        return "\n".join(f"    const val {name} = {number}" for name, number in rows)

    limit_lines = []
    for key, value in limits:
        # Keep the source value as a string: units and ranges are normative.
        escaped = value.replace('"', '\\"')
        limit_lines.append(f'    const val {key} = "{escaped}"')

    output = f'''package com.stille.coreapi

/** Generated by tools/generate_core_objects.py from core-src/core/docs/CORE-API.md. */
object GeneratedCoreApi {{
    const val API_VERSION = "{api_version}"

    object Method {{
{entries(methods)}
    }}

    object Event {{
{entries(events)}
    }}

    object Status {{
{entries(statuses)}
    }}

    object Limit {{
{chr(10).join(limit_lines)}
    }}
}}
'''
    OUT.write_text(output, encoding="utf-8")
    print(f"generated {OUT.relative_to(ROOT)}: {len(methods)} methods, {len(events)} events, {len(statuses)} statuses")


if __name__ == "__main__":
    main()
